#!/usr/bin/env node
// Usage: node tools/publish-collection.js <file> [--check-urls]
// Validates a curated collection (any item count ≥ 1, ranks 1..N, rules + sources).
// --check-urls curls every item and rule source (follow redirects, 15s). Non-2xx/3xx
// sets unverified: true on that source. 2xx/3xx clears unverified and sets checked
// to today (Asia/Shanghai). The file is written back; items are never dropped.
const fs = require('fs'), path = require('path'), cp = require('child_process');
const V = require('./rank-validate.js');
const root = path.resolve(__dirname, '..');
const args = process.argv.slice(2), file = args.find(a => !a.startsWith('--'));
if (!file) { console.error('usage: node tools/publish-collection.js <file> [--check-urls]'); process.exit(2); }

const target = path.resolve(file);
const data = JSON.parse(fs.readFileSync(target, 'utf8'));
const result = V.validateCollection(data);
if (!result.ok) { console.error('INVALID collection file:\n- ' + result.errors.join('\n- ')); process.exit(1); }

function curlCode(url) {
  return new Promise((resolve) => {
    cp.execFile('curl', ['-s', '-o', '/dev/null', '-L', '-A', 'Mozilla/5.0', '-w', '%{http_code}', '--max-time', '15', url], { timeout: 20000 }, (err, stdout) => {
      resolve(String(stdout || '').trim() || '000');
    });
  });
}
function mapPool(items, limit, fn) {
  const out = new Array(items.length);
  let cursor = 0;
  const n = Math.min(limit, items.length) || 0;
  const workers = [];
  for (let w = 0; w < n; w++) {
    workers.push((async function () {
      while (cursor < items.length) {
        const k = cursor++;
        out[k] = await fn(items[k], k);
      }
    })());
  }
  return Promise.all(workers).then(() => out);
}
function sourceLists() {
  const lists = [];
  (data.items || []).forEach(it => { if (it && Array.isArray(it.sources)) lists.push(it.sources); });
  (data.rules || []).forEach(rule => { if (rule && Array.isArray(rule.sources)) lists.push(rule.sources); });
  return lists;
}
function writeEmbed() {
  const dir = path.join(root, 'data/collections');
  const all = {};
  fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort().forEach(f => {
    const id = f.replace(/\.json$/, '');
    all[id] = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
  });
  const body = '/* AUTO-GENERATED by tools/publish-collection.js — do not edit */\nwindow.QUEST_COLLECTIONS = ' + JSON.stringify(all) + ';\n';
  fs.writeFileSync(path.join(root, 'js/collection-data.js'), body);
}
function writeBack() {
  fs.writeFileSync(target, JSON.stringify(data, null, 2) + '\n');
  writeEmbed();
}

if (!args.includes('--check-urls')) {
  writeEmbed();
  console.log('valid collection ' + (data.title || '') + ' (' + data.items.length + ' items, ' + data.rules.length + ' rules)');
  process.exit(0);
}

(async function () {
  const urls = [];
  sourceLists().forEach(list => list.forEach(s => { if (s && s.url && urls.indexOf(s.url) < 0) urls.push(s.url); }));
  (data.items || []).forEach(it => { if (it && it.source_url && urls.indexOf(it.source_url) < 0) urls.push(it.source_url); });
  const codes = {};
  await mapPool(urls, 6, async (u) => {
    const code = await curlCode(u);
    codes[u] = code;
    console.log(code + ' ' + u);
  });
  const today = V.todayShanghai();
  sourceLists().forEach(list => list.forEach(s => {
    if (!s || !s.url) return;
    const code = codes[s.url] || '000';
    if (/^[23]\d\d$/.test(code)) {
      if (s.unverified) delete s.unverified;
      s.checked = today;
    } else {
      s.unverified = true;
    }
  }));
  let unverified = 0;
  sourceLists().forEach(list => list.forEach(s => { if (s && s.unverified === true) unverified++; }));
  writeBack();
  console.log('unverified sources: ' + unverified);
  console.log('wrote ' + path.relative(root, target));
})().catch((err) => {
  console.error(err && err.stack ? err.stack : err);
  process.exit(1);
});
