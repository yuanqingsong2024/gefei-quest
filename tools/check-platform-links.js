#!/usr/bin/env node
/* 核实 js/platform-data.js 中的来源链接，输出 data/platform-links.json + js/platform-links.js（file:// 可用） */
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
global.window = {}; require(path.join(__dirname, '../js/platform-data.js'));
const urls = [...new Set(window.QUEST_PLATFORMS.PLATFORMS.flatMap(p => p.src.map(s => s[1])))];
const out = {};
for (const u of urls) {
  let code = '000';
  try { code = execFileSync('curl', ['-s', '-o', '/dev/null', '-L', '-m', '20', '-A', 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) Chrome/126 Safari/537.36', '-w', '%{http_code}', u]).toString().trim(); } catch (e) { code = (e.stdout || '000').toString().trim() || '000'; }
  out[u] = code; console.log(code, u);
}
const date = new Date().toISOString().slice(0, 10);
const data = { checked: date, total: urls.length, ok: Object.values(out).filter(c => c === '200').length, status: out };
fs.writeFileSync(path.join(__dirname, '../data/platform-links.json'), JSON.stringify(data, null, 1));
fs.writeFileSync(path.join(__dirname, '../js/platform-links.js'), '/* generated by tools/check-platform-links.js */\nwindow.QUEST_PLATFORM_LINKS = ' + JSON.stringify(data) + ';\n');
console.log('ok', data.ok, '/', data.total);
