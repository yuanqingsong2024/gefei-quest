#!/usr/bin/env python3
"""Bundle docs/*.md (and TASKS/TESTLOG) into js/guides-data.js so guides render under file:// too."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
files = sorted((root / 'docs').glob('*.md')) + [root / 'TASKS.md', root / 'TESTLOG.md']
data = {}
for f in files:
    if f.exists():
        key = f.stem if f.parent.name == 'docs' else f.stem
        data[key] = f.read_text(encoding='utf-8')
out = root / 'js' / 'guides-data.js'
out.write_text('/* AUTO-GENERATED by tools/build-guides.py — do not edit */\n'
               'window.QUEST_GUIDES_MD = ' + json.dumps(data, ensure_ascii=False) + ';\n', encoding='utf-8')
print('bundled', len(data), 'docs ->', out.relative_to(root))
