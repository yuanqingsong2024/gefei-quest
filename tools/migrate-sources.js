#!/usr/bin/env node
/** Idempotent: add sources[] to every rank item from source_url.
 *  publisher = hostname without www.; title/published stay ''; kind by domain rules;
 *  checked = that file's date. Never invent titles/dates. Then rebuild js/rank-data.js. */
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..');
const QS = require('../js/sources.js');

function walk(dir, acc) {
  if (!fs.existsSync(dir)) return acc;
  fs.readdirSync(dir).forEach((f) => {
    const p = path.join(dir, f);
    if (fs.statSync(p).isDirectory()) return walk(p, acc);
    if (f === 'index.json') return;
    if (/\.json$/.test(f)) acc.push(p);
  });
  return acc;
}

function ensureItem(it, date) {
  if (!it || typeof it !== 'object') return 'skip';
  if (Array.isArray(it.sources) && it.sources.length) {
    it.sources = it.sources.map((s) => {
      const url = (s && s.url) || it.source_url || '';
      const next = {
        title: s && s.title != null ? String(s.title) : '',
        url: url,
        publisher: (s && s.publisher) ? String(s.publisher) : QS.hostOf(url),
        published: s && s.published != null ? String(s.published) : '',
        kind: (s && s.kind) || QS.kindOf(url),
        checked: (s && s.checked) ? String(s.checked) : date,
      };
      return next;
    });
    if (!it.source_url) it.source_url = it.sources[0].url;
    return 'kept';
  }
  if (typeof it.source_url === 'string' && it.source_url.trim()) {
    it.sources = [QS.fromLegacy(it.source_url, date)];
    return 'added';
  }
  return 'skip';
}

function migrateFile(file) {
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  const date = data.date || path.basename(file, '.json');
  const items = Array.isArray(data.items) ? data.items : [];
  let added = 0, kept = 0, skip = 0;
  items.forEach((it) => {
    const r = ensureItem(it, date);
    if (r === 'added') added++;
    else if (r === 'kept') kept++;
    else skip++;
  });
  fs.writeFileSync(file, JSON.stringify(data, null, 2) + '\n');
  return { file: path.relative(root, file), date, n: items.length, added, kept, skip };
}

const files = [];
files.push(path.join(root, 'data/rank.json'));
walk(path.join(root, 'data/rank-history'), files);
walk(path.join(root, 'data/money-rank'), files);
const seen = {};
const reports = [];
files.filter((f) => fs.existsSync(f) && !seen[f] && (seen[f] = 1)).forEach((f) => {
  reports.push(migrateFile(f));
});

const hist = path.join(root, 'data/rank-history');
const dates = fs.readdirSync(hist).filter((f) => /^\d{4}-\d{2}-\d{2}\.json$/.test(f)).map((f) => f.slice(0, 10)).sort().reverse();
const latestFile = path.join(root, 'data/rank.json');
const latest = fs.existsSync(latestFile) ? JSON.parse(fs.readFileSync(latestFile, 'utf8')).date : dates[0];
const embed = {};
dates.slice(0, 14).forEach((d) => {
  embed[d] = JSON.parse(fs.readFileSync(path.join(hist, d + '.json'), 'utf8'));
});
fs.writeFileSync(
  path.join(root, 'js/rank-data.js'),
  '/* AUTO-GENERATED by tools/publish-rank.js — do not edit */\nwindow.QUEST_RANK = ' +
    JSON.stringify({ latest: latest, dates: dates, days: embed }) + ';\n'
);

reports.forEach((r) => {
  console.log(r.file + ' items=' + r.n + ' added=' + r.added + ' kept=' + r.kept + ' skip=' + r.skip);
});
console.log('rank-data.js latest=' + latest + ' days=' + dates.length);
